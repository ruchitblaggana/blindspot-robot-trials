export const getTrial = (id: string): TrialDef | undefined => TRIALS.find((t) => t.id === id);

export const isTrialUnlocked = (index: number, completedTrials: Set<string>): boolean => {
  if (index === 1) return true;
  const prev = TRIALS.find((t) => t.index === index - 1);
  if (!prev) return false;
  return completedTrials.has(prev.id);
};

